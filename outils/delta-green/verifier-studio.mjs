import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

const root=process.cwd();
const output=path.join(root,'tmp/delta-green-studio');
const html=path.join(root,'docs/fiches/Delta Green/delta-green-fiche-agent-interactive.html');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1400,height:1100},deviceScaleFactor:2,acceptDownloads:true});
const network=[],errors=[];
await context.route(/^https?:/,route=>{network.push(route.request().url());return route.abort();});
const page=await context.newPage();
page.on('pageerror',error=>errors.push(error.message));
const field=key=>page.locator(`[data-key="${key}"]`).first();
try {
 await page.goto(pathToFileURL(html).href);
 await page.waitForSelector('.dg-field');
 assert.equal(await page.locator('.dg-field').count(),239);
 await field('identity.name').fill('AGENT MERCIER');
 await field('identity.profession').fill('Analyste du renseignement');
 await field('attributes.strength').fill('11');
 await field('attributes.constitution').fill('13');
 await field('attributes.power').fill('12');
 assert.equal(await field('attributes.strength_x5').inputValue(),'55');
 assert.equal(await field('health.hp_max').inputValue(),'12');
 assert.equal(await field('health.willpower_max').inputValue(),'12');
 await field('skills.unnatural').fill('7');
 assert.equal(await field('health.sanity_max').inputValue(),'92');
 await field('health.hp').fill('10');
 await field('health.sanity').fill('57');
 await field('health.breaking_point').fill('45');
 await field('skills.firearms').fill('62');
 await field('bonds.0.name').fill('Camille, sœur');
 await field('bonds.0.score').fill('11');
 await field('experience.firearms').check();
 const violence=page.locator('button[data-key="adaptation.violence"]');
 await violence.nth(1).click();
 assert.equal(await page.locator('button[data-key="adaptation.violence"].active').count(),2);
 await page.reload();
 assert.equal(await field('identity.name').inputValue(),'AGENT MERCIER');
 assert.equal(await field('skills.firearms').inputValue(),'62');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Exporter JSON',exact:true}).click();
 const download=await downloadPromise;
 const exported=path.join(output,'agent-test.json');await download.saveAs(exported);
 const json=JSON.parse(fs.readFileSync(exported,'utf8'));assert.equal(json.data.identity.name,'AGENT MERCIER');
 await page.evaluate(()=>zoom(1));
 await page.getByRole('button',{name:'Zones',exact:true}).click();
 await page.locator('.sheet').nth(0).screenshot({path:path.join(output,'fiche-page-1-zones.png')});
 await page.locator('.sheet').nth(1).screenshot({path:path.join(output,'fiche-page-2-zones.png')});
 await page.getByRole('button',{name:'Zones',exact:true}).click();
 await page.locator('.sheet').nth(0).screenshot({path:path.join(output,'fiche-page-1-remplie.png')});
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Réinitialiser',exact:true}).click();
 assert.equal(await field('identity.name').inputValue(),'');
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#file').setInputFiles(exported);
 await page.waitForFunction(()=>document.querySelector('[data-key="identity.name"]').value==='AGENT MERCIER');
 await page.getByRole('combobox',{name:'Page',exact:true}).selectOption('1');
 assert.equal(await page.getByRole('combobox',{name:'Page',exact:true}).inputValue(),'1');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.keyboard.press('Control+-');
 assert.equal(await page.locator('#zoom').textContent(),'90 %');
 await page.keyboard.press('Control++');
 assert.equal(await page.locator('#zoom').textContent(),'100 %');
 await page.pdf({path:path.join(output,'fiche-impression.pdf'),printBackground:true,preferCSSPageSize:true});
 assert.deepEqual(errors,[]);
 assert.deepEqual(network,[]);
 fs.writeFileSync(path.join(output,'fiche-verification.json'),JSON.stringify({pages:2,zones:239,erreursJavaScript:errors,requetesReseau:network,verifie:['saisie','calculs imprimés','pistes','cases expérience','sauvegarde et rechargement','export JSON','import JSON','réinitialisation','navigation','zoom clavier','impression deux pages','captures Zones']},null,2));
 console.log('Fiche : parcours autonome vérifié, aucune erreur JavaScript, aucune requête réseau.');
} finally {await browser.close();}
