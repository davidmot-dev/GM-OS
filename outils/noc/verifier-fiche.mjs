import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
const fichier = 'docs/fiches/NOC/NOC_fiche_personnage_interactive_pixel_recale_v3.html';
const moteur = 'docs/fiches/Character_Sheet_Manager.html';
const extraire = source => JSON.parse(source.match(/<script[^>]*id=["']character-sheet-template["'][^>]*>([\s\S]*?)<\/script>/i)[1]).template;
const modele = extraire(fs.readFileSync(fichier, 'utf8'));
const avant = extraire(execFileSync('git', ['show', `HEAD:${fichier}`], { encoding: 'utf8', maxBuffer: 15_000_000 }));
const cles = new Set(modele.pages.flatMap(p => p.fields.map(f => f.key)));
for (const p of avant.pages) { assert.equal(p.backgroundData, modele.pages.find(q => q.id === p.id).backgroundData); for (const f of p.fields) assert.ok(cles.has(f.key), f.key); }
const vieux = { 'identity.name': 'Ilse Novak', 'tracks.vecu.1': true, 'tracks.vecu.3': '1', 'tracks.vecu.8': true, 'tracks.trauma.7': true };
fs.mkdirSync('tmp/noc-fin/captures', { recursive: true });
fs.writeFileSync('tmp/noc-fin/ancienne-fiche.json', JSON.stringify({ format: 'interactive-character-sheet', version: 1, sheet: 'noc-reference', data: vieux }));
const navigateur = await chromium.launch({ channel: 'msedge', headless: true });
try {
    const contexte = await navigateur.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    await contexte.setOffline(true);
    const erreurs = [], reseau = [];
    await contexte.route('**/*', r => ['file:', 'data:', 'blob:'].includes(new URL(r.request().url()).protocol) ? r.continue() : (reseau.push(r.request().url()), r.abort()));
    const page = await contexte.newPage(); page.on('pageerror', e => erreurs.push(e.message));
    await page.goto(pathToFileURL(path.resolve(fichier)).href);
    await page.locator('#loadJson').setInputFiles('tmp/noc-fin/ancienne-fiche.json');
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('noc-character-sheet-v1'))?.['tracks.vecu'] === 3);
    assert.equal(await page.locator('[data-track="tracks.vecu"].active').count(), 3);
    assert.equal(await page.locator('[data-track="tracks.trauma"].active').count(), 1);
    await page.locator('[data-track="tracks.vecu"][data-value="6"]').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('noc-character-sheet-v1'))?.['tracks.vecu'] === 6);
    await page.reload(); assert.equal(await page.locator('[data-track="tracks.vecu"].active').count(), 6);
    await page.locator('#sheet').screenshot({ path: 'tmp/noc-fin/captures/fiche-autonome.png' });
    await page.locator('[data-track="tracks.vecu"][data-value="6"]').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('noc-character-sheet-v1'))?.['tracks.vecu'] === 0);
    const telecharge = page.waitForEvent('download'); await page.locator('#saveJson').click();
    await (await telecharge).saveAs('tmp/noc-fin/export-autonome.json');
    const json = JSON.parse(fs.readFileSync('tmp/noc-fin/export-autonome.json'));
    for (const k of modele.legacySeries['tracks.vecu']) assert.equal(json.data[k], false);
    const moteurPage = await contexte.newPage(); moteurPage.on('pageerror', e => erreurs.push(e.message));
    await moteurPage.goto(pathToFileURL(path.resolve(moteur)).href); await moteurPage.waitForFunction(() => !!window.RPGSheet);
    const perso = await moteurPage.evaluate(data => window.RPGSheet.create('Ancien Héros NOC', 'noc-reference', data), vieux);
    assert.equal(perso.data['tracks.vecu'], 3);
    await moteurPage.locator('.hotspot[data-key="tracks.vecu"][data-value="7"]').click();
    const courant = await moteurPage.evaluate(() => window.RPGSheet.getData());
    assert.equal(courant.data['tracks.vecu'], 7);
    assert.equal(modele.legacySeries['tracks.vecu'].filter(k => courant.data[k]).length, 7);
    await moteurPage.evaluate(() => window.RPGSheet.setData({ 'tracks.vecu': 12 }));
    assert.equal((await moteurPage.evaluate(() => window.RPGSheet.getData())).data['tracks.vecu'], 12);
    await moteurPage.evaluate(() => window.RPGSheet.setData({ 'tracks.vecu': 6 }));
    await moteurPage.locator('.sheet').screenshot({ path: 'tmp/noc-fin/captures/fiche-moteur.png' });
    await moteurPage.waitForTimeout(250);
    await moteurPage.reload(); await moteurPage.waitForFunction(() => !!window.RPGSheet);
    const revenu = await moteurPage.evaluate(id => window.RPGSheet.openCharacter(id), perso.id);
    assert.equal(revenu.data['tracks.vecu'], 6);
    const ancienMoteur = execFileSync('git', ['show', `HEAD:${moteur}`], { encoding: 'utf8', maxBuffer: 35_000_000 });
    const lireModeles = s => JSON.parse(s.match(/<script id="builtinTemplates" type="application\/json">([\s\S]*?)<\/script>/)[1]);
    assert.deepEqual(lireModeles(fs.readFileSync(moteur, 'utf8')).filter(t => t.id !== 'noc-reference'), lireModeles(ancienMoteur).filter(t => t.id !== 'noc-reference'));
    assert.deepEqual(erreurs, []); assert.deepEqual(reseau, []);
    const rapport = { modele: modele.id, pistes: 9, anciennesClesConservees: 78, ancienneSauvegarde: true, clicCumulatif: true, remiseAZero: true,
        exportJSON: true, rechargement: true, migrationMoteur: true, valeursSuperieuresAuxCasesConservees: true, autresModelesInchanges: true, erreurs, reseau };
    fs.writeFileSync('tmp/noc-fin/verification-fiche.json', JSON.stringify(rapport, null, 2)); console.log(JSON.stringify(rapport));
} finally { await navigateur.close(); }
